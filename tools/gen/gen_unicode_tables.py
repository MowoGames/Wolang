#!/usr/bin/env python3
"""Generates include/wolang/base/unicode_tables.inc.

The lexer needs three Unicode facts: which code points may start or continue
an identifier (XID_Start / XID_Continue), and whether a sequence is already in
NFC form. Shipping generated tables keeps the compiler free of a Unicode
library while staying reproducible: rerun this script to move to a new Unicode
version.

    python3 tools/gen/gen_unicode_tables.py > include/wolang/base/unicode_tables.inc
"""

import sys
import unicodedata

MAX = 0x110000
# Hangul syllable composition is arithmetic, so it is excluded from the pair
# table and handled in code instead.
HANGUL_L_BASE = 0x1100
HANGUL_V_BASE = 0x1161
HANGUL_T_BASE = 0x11A7
HANGUL_S_BASE = 0xAC00
HANGUL_L_COUNT = 19
HANGUL_V_COUNT = 21
HANGUL_T_COUNT = 28
HANGUL_N_COUNT = HANGUL_V_COUNT * HANGUL_T_COUNT
HANGUL_S_COUNT = HANGUL_L_COUNT * HANGUL_N_COUNT


def to_ranges(code_points):
    """Collapses a sorted iterable of code points into [begin, end] ranges."""
    result = []
    begin = previous = None
    for cp in code_points:
        if begin is None:
            begin = previous = cp
        elif cp == previous + 1:
            previous = cp
        else:
            result.append((begin, previous))
            begin = previous = cp
    if begin is not None:
        result.append((begin, previous))
    return result


def value_ranges(pairs):
    """Collapses sorted (code point, value) pairs into [begin, end, value]."""
    result = []
    begin = previous = None
    value = None
    for cp, v in pairs:
        if begin is None:
            begin = previous = cp
            value = v
        elif cp == previous + 1 and v == value:
            previous = cp
        else:
            result.append((begin, previous, value))
            begin = previous = cp
            value = v
    if begin is not None:
        result.append((begin, previous, value))
    return result


def emit_ranges(name, ranges):
    print(f"#ifdef {name}")
    for begin, end in ranges:
        print(f"{name}(0x{begin:04X}, 0x{end:04X})")
    print(f"#undef {name}")
    print("#endif")
    print()


def main():
    # Python identifiers use XID_Start and XID_Continue exactly, so the
    # standard library is the authority and no UCD file has to be parsed.
    xid_start = [
        cp for cp in range(0x80, MAX) if chr(cp).isidentifier()
    ]
    xid_continue = [
        cp for cp in range(0x80, MAX) if ("a" + chr(cp)).isidentifier()
    ]

    combining = [
        (cp, unicodedata.combining(chr(cp)))
        for cp in range(MAX)
        if unicodedata.combining(chr(cp))
    ]

    # A canonical composition pair counts only when NFC actually produces the
    # composite, which filters out the composition exclusions.
    pairs = {}
    for cp in range(MAX):
        decomposition = unicodedata.decomposition(chr(cp))
        if not decomposition or decomposition.startswith("<"):
            continue
        parts = decomposition.split()
        if len(parts) != 2:
            continue
        first, second = int(parts[0], 16), int(parts[1], 16)
        if HANGUL_S_BASE <= cp < HANGUL_S_BASE + HANGUL_S_COUNT:
            continue
        if unicodedata.normalize("NFC", chr(first) + chr(second)) == chr(cp):
            pairs[(first, second)] = cp

    # NFC_QC = No: NFC rewrites the code point on its own.
    nfc_no = [
        cp
        for cp in range(MAX)
        if unicodedata.normalize("NFC", chr(cp)) != chr(cp)
    ]
    # NFC_QC = Maybe: the code point can be the second half of a composition.
    nfc_maybe = sorted({second for _, second in pairs})

    print("// Copyright 2026 The Wolang Authors. All rights reserved.")
    print("//")
    print("// Generated by tools/gen/gen_unicode_tables.py. Do not edit.")
    print(f"// Unicode {unicodedata.unidata_version}")
    print()

    emit_ranges("WOLANG_XID_START_RANGE", to_ranges(xid_start))
    emit_ranges("WOLANG_XID_CONTINUE_RANGE", to_ranges(xid_continue))
    emit_ranges("WOLANG_NFC_NO_RANGE", to_ranges(nfc_no))
    emit_ranges("WOLANG_NFC_MAYBE_RANGE", to_ranges(nfc_maybe))

    print("#ifdef WOLANG_COMBINING_CLASS_RANGE")
    for begin, end, value in value_ranges(combining):
        print(
            f"WOLANG_COMBINING_CLASS_RANGE(0x{begin:04X}, 0x{end:04X}, {value})"
        )
    print("#undef WOLANG_COMBINING_CLASS_RANGE")
    print("#endif")
    print()

    print("#ifdef WOLANG_COMPOSITION_PAIR")
    for (first, second), composed in sorted(pairs.items()):
        print(
            f"WOLANG_COMPOSITION_PAIR(0x{first:04X}, 0x{second:04X},"
            f" 0x{composed:04X})"
        )
    print("#undef WOLANG_COMPOSITION_PAIR")
    print("#endif")


if __name__ == "__main__":
    main()

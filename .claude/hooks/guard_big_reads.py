#!/usr/bin/env py
"""PreToolUse guard: no whole-file reads of the repository's giant files.

A handful of files would each cost 30k-75k tokens to read in one go:
src/ir/lower.cc, src/sema/type_check.cc, tools/wolang/main.cc, the two
emitters, docs/decisions.md and the generated unicode tables. Reading one
whole is almost never what a task needs; finding the function first is.

This hook refuses a Read without `offset`/`limit` on any file larger than
LIMIT bytes, and a Bash `cat`/`less`/`more` of one, and says what to do
instead. Exit code 2 sends the message back to the model, which then
retries with a narrower read. Anything it cannot parse is let through.
"""

import json
import os
import re
import shlex
import sys

LIMIT = 60_000  # bytes, roughly 15k tokens

ADVICE = {
    "docs/decisions.md": (
        "Use `.claude/scripts/decision D<n>` for one decision, "
        "`decision -s <regex>` to find which, `decision -l` for titles."
    ),
    "include/wolang/base/unicode_tables.inc": (
        "Generated by tools/gen/gen_unicode_tables.py -- read or change "
        "the script, never the table."
    ),
}


def too_big(path, cwd):
    if not path:
        return None
    full = path if os.path.isabs(path) else os.path.join(cwd, path)
    try:
        size = os.path.getsize(full)
    except OSError:
        return None
    if size <= LIMIT:
        return None
    root = os.environ.get("CLAUDE_PROJECT_DIR", cwd)
    rel = os.path.relpath(os.path.realpath(full), os.path.realpath(root))
    return rel, size


def refuse(rel, size):
    tip = ADVICE.get(
        rel,
        "Grep for the symbol first (Grep with -n, or `rg -n`), then Read "
        "with offset/limit around the hit (200-400 lines is plenty).",
    )
    sys.stderr.write(
        f"{rel} is {size // 1024} KB (~{size // 4000}k tokens); reading it "
        f"whole is blocked to save context. {tip}\n"
    )
    sys.exit(2)


def main():
    try:
        event = json.load(sys.stdin)
    except ValueError:
        return
    tool = event.get("tool_name")
    data = event.get("tool_input") or {}
    cwd = event.get("cwd") or os.getcwd()

    if tool == "Read":
        if data.get("offset") or data.get("limit"):
            return
        hit = too_big(data.get("file_path"), cwd)
        if hit:
            refuse(*hit)
    elif tool == "Bash":
        command = data.get("command", "")
        # Only a bare dump: `cat big`, not `cat big | head` or `grep x big`.
        if "|" in command or not re.match(r"\s*(cat|less|more)\s", command):
            return
        try:
            words = shlex.split(command)
        except ValueError:
            return
        for word in words[1:]:
            if word.startswith("-"):
                continue
            hit = too_big(word, cwd)
            if hit:
                refuse(*hit)


if __name__ == "__main__":
    main()
